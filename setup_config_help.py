#!/usr/bin/env python3
"""Дописывает в лист «Конфиг» памятку по столбцам и примеры строк.

Пишет НИЖЕ существующих данных (по умолчанию с 40-й строки) и ничего не
затирает: разложить по местам админ сможет сам.

Запуск:  venv/bin/python setup_config_help.py [--row 40]
"""

import argparse

from report_common import init_sheets

SHEET = "Конфиг"

BLOCK = [
    ["--- ПАМЯТКА: ТУРНИРЫ КОМАНДЫ (дописано ботом) ---"],
    [""],
    ["Столбец", "Что писать", "Инфобаскет", "SLPRO"],
    ["ТИП", "Откуда берём статистику. Выпадающий список.",
     "ИНФОБАСКЕТ", "SLPRO"],
    ["ИД (СОРЕВНОВАНИЯ)", "Инфобаскет: compId из ссылки. SLPRO: КОД ДИВИЗИОНА из ссылки.",
     "140825", "SUMC"],
    ["ИД КОМАНДЫ", "Инфобаскет: teamId из ссылки. SLPRO: НАЗВАНИЕ команды — "
     "числового id на сайте не видно.", "36502", "PullUp Farm"],
    ["АЛЬТЕРНАТИВНОЕ ИМЯ", "Как показывать турнир в боте и админке. Можно пусто.",
     "Летняя лига", "Летний Кубок Дивизион C"],
    [""],
    ["Как найти значения:"],
    ["Инфобаскет", "Открой страницу команды. В адресе: compId=140825 и teamId=36502."],
    ["SLPRO", "Открой страницу турнира. В адресе код дивизиона, например SUMC. "
              "Название команды пиши как на сайте — бот сам найдёт нужную стадию и сезон."],
    [""],
    ["Что делает бот:"],
    ["", "Опросы, анонсы и результаты — по каждому турниру из этого списка."],
    ["", "Эти же турниры предлагаются в фэнтези (приложение → ⚙️ → «Можно добавить»)."],
    ["", "Турнир закончился — удали строку, и бот перестанет туда ходить."],
    ["", "Начался новый — добавь строку, ничего перезапускать не нужно."],
    [""],
    ["--- ПРИМЕРЫ (заполни своими и перенеси наверх) ---"],
    ["ТИП", "ИД (СОРЕВНОВАНИЯ)", "ИД КОМАНДЫ / НАЗВАНИЕ", "АЛЬТЕРНАТИВНОЕ ИМЯ"],
    ["ИНФОБАСКЕТ", "140825", "36502", "Летняя лига · Группа 4"],
    ["SLPRO", "SUMC", "PullUp Farm", "Летний Кубок Дивизион C"],
]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--row", type=int, default=40, help="с какой строки писать")
    args = ap.parse_args()

    ws = init_sheets().worksheet(SHEET)
    if ws.row_count < args.row + len(BLOCK):
        ws.add_rows(args.row + len(BLOCK) - ws.row_count + 10)

    width = max(len(r) for r in BLOCK)
    body = [r + [""] * (width - len(r)) for r in BLOCK]
    end_col = chr(ord("A") + width - 1)
    rng = f"A{args.row}:{end_col}{args.row + len(body) - 1}"
    ws.update(rng, body, value_input_option="USER_ENTERED")
    print(f"✅ Памятка записана в «{SHEET}», диапазон {rng}")
    print("   Ничего существующего не затронуто — блок дописан ниже.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
